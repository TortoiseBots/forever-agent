func hmacSHA512(key []byte, parts ...[]byte) []byte {
	m := hmac.New(sha512.New, key)
	for _, p := range parts {
		m.Write(p)
	}
	return m.Sum(nil)
}

func sha512Of(parts ...[]byte) []byte {
	h := sha512.New()
	for _, p := range parts {
		h.Write(p)
	}
	return h.Sum(nil)
}

// sessionKeyFrom derives the 40-byte world session key: SHA512(keyData), then an HMAC-SHA512 over the server
// challenge, the local challenge and SessionKeySeed, run through the core's SessionKeyGenerator<SHA512>
// (WorldSocket.cpp:800-806, SessionKeyGenerator.h:28-52).
func sessionKeyFrom(keyData, serverChallenge, localChallenge []byte) [40]byte {
	seed := hmacSHA512(sha512Of(keyData), serverChallenge, localChallenge, sessionKeySeed[:])
	// SessionKeyGenerator: o1 = H(seed[0:32]), o2 = H(seed[32:64]), o0 = H(o1 || o0 || o2) with o0 initialised to
	// zeros; the first 40 generated bytes are the first 40 bytes of o0 (the digest is 64 bytes, so no rehash)
	half := len(seed) / 2
	o1 := sha512Of(seed[:half])
	o2 := sha512Of(seed[half:])
	o0 := sha512Of(o1, make([]byte, sha512.Size), o2)
	var out [40]byte
	copy(out[:], o0[:40])
	return out
}

// encryptKeyFrom derives the 32-byte AES-256-GCM key: HMAC-SHA512(sessionKey, localChallenge ||
// serverChallenge || EncryptionKeySeed), first 32 bytes (WorldSocket.cpp:808-816).
func encryptKeyFrom(sessionKey, localChallenge, serverChallenge []byte) [32]byte {
	digest := hmacSHA512(sessionKey, localChallenge, serverChallenge, encryptionKeySeed[:])
	var out [32]byte
	copy(out[:], digest[:32])
	return out
}

// authDigest is the 24-byte CMSG_AUTH_SESSION digest:
// HMAC-SHA512(SHA512(keyData || buildAuthKey), localChallenge || serverChallenge || AuthCheckSeed)[0:24]
// (WorldSocket.cpp:775-791). The server skips the comparison when Network.SkipBuildAuthKeyCheck is set and the
// build has no build_auth_key row for the ticket's variant (WorldSocket.cpp:756-772); the live auth database has
// no row for 70707 or 70938, so this client sends 24 zero bytes and the server never looks at them. The function
// exists so the skipped step is written down and can be checked against a vector.
func authDigest(keyData, buildAuthKey, localChallenge, serverChallenge []byte) [24]byte {
	digest := hmacSHA512(sha512Of(keyData, buildAuthKey), localChallenge, serverChallenge, authCheckSeed[:])
	var out [24]byte
	copy(out[:], digest[:24])
	return out
}

// continuedSessionDigest is the 24-byte CMSG_AUTH_CONTINUED_SESSION digest:
// HMAC-SHA512(sessionKey, LE64(key) || localChallenge || instanceServerChallenge || ContinuedSessionSeed)[0:24]
// (WorldSocket.cpp:1040-1047). Unlike the realm's digest this one is always checked, so a wrong session key or a
// misread Key fails here rather than at the first encrypted packet.
func continuedSessionDigest(sessionKey []byte, key uint64, localChallenge, serverChallenge []byte) [24]byte {
	var keyBytes [8]byte
	binary.LittleEndian.PutUint64(keyBytes[:], key)
	digest := hmacSHA512(sessionKey, keyBytes[:], localChallenge, serverChallenge, continuedSessionSeed[:])
	var out [24]byte
	copy(out[:], digest[:24])
	return out
}

// enableEncryptionSignature is the 64-byte Ed25519 signature input the server signs: HMAC-SHA512(encryptKey,
// 0x01 || EnableEncryptionSeed). This client cannot verify the signature (the public key the client build trusts
// for RegionGroup 8 is not in the server tree, the recorder's captures or this repository), so it is parsed and
// reported, not checked; what authenticates the server here is the AES-GCM tag of the first encrypted packet,
// which needs the join secret. Kept as a function so the notes and the tests can state exactly what is signed.
func enableEncryptionSignatureInput(encryptKey []byte) [64]byte {
	digest := hmacSHA512(encryptKey, []byte{1}, enableEncryptionSeed[:])
	var out [64]byte
	copy(out[:], digest)
	return out
}

// checkKeyData validates the 64 bytes the Battle.net join stored: the client secret followed by the join secret.
// The world server reads the same 64 bytes from account.session_key_bnet (WorldSocket.cpp:796).
func checkKeyData(clientSecret, joinSecret []byte) ([64]byte, error) {
	var keyData [64]byte
	if len(clientSecret) != 32 || len(joinSecret) != 32 {
		return keyData, fmt.Errorf("worldconn: key data needs a 32-byte client secret and a 32-byte join secret, got %d and %d bytes", len(clientSecret), len(joinSecret))
	}
	copy(keyData[:32], clientSecret)
	copy(keyData[32:], joinSecret)
	return keyData, nil
}
